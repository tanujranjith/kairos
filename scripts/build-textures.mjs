import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {encodeToKTX2} from 'ktx2-encoder';
import {surfaceKinds,surfacePixels,cloudAtlas} from '../src/render/texture-fields.mjs';

const outputRoot='public/textures',surfaceRoot=path.join(outputRoot,'surface'),sha=data=>createHash('sha256').update(data).digest('hex');
await fs.mkdir(surfaceRoot,{recursive:true});
const entries=[];
async function encode(name,pixels,width,height,kind){
  const normal=kind==='normal',linear=normal||kind==='cloud';
  const data=await encodeToKTX2(new Uint8Array(),{
    imageDecoder:async()=>({data:pixels,width,height}),isKTX2File:true,generateMipmap:true,
    isUASTC:linear,qualityLevel:192,compressionLevel:4,needSupercompression:linear,
    uastcLDRQualityLevel:2,enableRDO:linear,rdoQualityLevel:1,
    isNormalMap:normal,isPerceptual:!linear,isSetKTX2SRGBTransferFunc:!linear,
    kvData:{'KTXwriter':'Kairos texture build','kairos.source':'original procedural field'},
  });
  const target=path.join(outputRoot,name);await fs.writeFile(target,data);
  entries.push({file:name.replaceAll('\\','/'),width,height,kind,encoding:linear?'UASTC+Zstd':'ETC1S',bytes:data.byteLength,sha256:sha(data)});
  console.log(`${name}: ${data.byteLength} bytes (${linear?'UASTC+Zstd':'ETC1S'})`);
}
for(const kind of surfaceKinds){
  const pixels=surfacePixels(kind,256);
  await encode(path.join('surface',`${kind}-albedo.ktx2`),pixels.color,256,256,'albedo');
  await encode(path.join('surface',`${kind}-normal.ktx2`),pixels.normal,256,256,'normal');
}
await encode('cloud-density.ktx2',cloudAtlas(512),512,512,'cloud');
const generator=await fs.readFile('src/render/texture-fields.mjs'),builder=await fs.readFile('scripts/build-textures.mjs');
const assetVersion=sha(entries.map(entry=>entry.sha256).join('\n')).slice(0,16);
const manifest={version:1,assetVersion,generator:'src/render/texture-fields.mjs',generatorSha256:sha(generator),builder:'scripts/build-textures.mjs',builderSha256:sha(builder),generatedBy:'ktx2-encoder 0.6.0 / Basis Universal',entries,totalBytes:entries.reduce((sum,entry)=>sum+entry.bytes,0)};
await fs.writeFile(path.join(outputRoot,'manifest.json'),`${JSON.stringify(manifest,null,2)}\n`);
await fs.writeFile('src/render/texture-version.ts',`/** Generated by scripts/build-textures.mjs. Do not edit by hand. */\nexport const TEXTURE_ASSET_VERSION='${assetVersion}';\nexport const textureAssetUrl=(path:string)=>\`${'${path}'}?v=${'${TEXTURE_ASSET_VERSION}'}\`;\n`);
console.log(`Wrote ${entries.length} textures, ${manifest.totalBytes} bytes total.`);
